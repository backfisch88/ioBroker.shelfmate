#!/usr/bin/env python3
"""Builds www/productSuggestions.js from tools/productSuggestions.txt (sections start with '# ')."""
import glob, json, os, re, sys
src, dst = sys.argv[1], sys.argv[2]
trdir = sys.argv[3] if len(sys.argv) > 3 else os.path.join(os.path.dirname(os.path.abspath(src)), "productTranslations")
tr = []
for f in sorted(glob.glob(os.path.join(trdir, "*.txt"))):
    for l in open(f, encoding="utf8"):
        l = l.rstrip("\n")
        if l.strip():
            parts = l.split("|")
            assert len(parts) == 11 and all(x.strip() for x in parts), (f, l)
            tr.append([x.strip() for x in parts])
SEC = {
    'Baby Kind': 'Lebensmittel',
    'Haushalt Hygiene': 'Haushalt',
}
DROG = r'^(Babyshampoo|Babywaschlotion|Feuchttücher|Wundschutzcreme|Windeln|Schnuller|Lätzchen|Conditioner|Damenbinden|Deo|Deodorant|Duschgel|Haarspülung|Handcreme|Handseife|Flüssigseife|Lippenpflege|Körperlotion|Mundspülung|Pflaster|Rasier.*|Shampoo|Slipeinlagen|Sonnencreme|Tampons|Taschentücher|Kosmetiktücher|Wattepads|Wattestäbchen|Zahnbürste|Zahnpasta|Zahnseide|Desinfektionsmittel)$'
TIER = r'^(Hundefutter|Hundeleckerlis|Katzenfutter|Katzenstreu)$'
BABYFOOD_NON = r'^(Babyshampoo|Babywaschlotion|Feuchttücher|Wundschutzcreme|Windeln|Schnuller|Lätzchen)$'
tagmap = {}
tagfile = os.path.join(os.path.dirname(os.path.abspath(src)), 'productTags.txt')
for l in open(tagfile, encoding='utf8'):
    l = l.rstrip('\n')
    if l and not l.startswith('#'):
        a, b = l.split('|')
        tagmap[a] = b
multi = {}
for l in open(os.path.join(os.path.dirname(os.path.abspath(src)), 'tagLabels', 'multiTags.txt'), encoding='utf8'):
    parts = l.rstrip('\n').split('|')
    if len(parts) == 12:
        assert all(x.strip() for x in parts), parts
        multi['en:' + parts[0]] = [x.strip() for x in parts[1:]]
tags, tagidx = [], {}
out, sec = [], ''
for line in open(src, encoding='utf8'):
    t = line.strip()
    if not t:
        continue
    if t.startswith('# '):
        sec = t[2:]
        continue
    cat = 'Lebensmittel'
    if sec == 'Haushalt Hygiene':
        cat = 'Tierbedarf' if re.match(TIER, t) else 'Drogerie' if re.match(DROG, t) else 'Haushalt'
    elif sec == 'Baby Kind' and re.match(BABYFOOD_NON, t):
        cat = 'Drogerie'
    i = len(out)
    assert i < len(tr) and tr[i][0] == t, ('translation mismatch', i, t)
    tid = tagmap.get(t, '')
    if tid and cat == 'Lebensmittel':
        if tid not in tagidx:
            labels = multi.get(tid, tr[i])
            tagidx[tid] = len(tags)
            tags.append([tid, labels])
        out.append([t, cat, tr[i][1:], tagidx[tid]])
    else:
        out.append([t, cat, tr[i][1:]])
js = '/* generated by tools/buildSuggestions.py from tools/productSuggestions.txt */\nwindow.PRODUCT_SUGGESTION_LANGS=["en","ru","pt","nl","fr","it","es","pl","uk","zh-cn"];\nwindow.PRODUCT_TAGS=' + json.dumps(tags, ensure_ascii=False, separators=(',', ':')) + ';\nwindow.PRODUCT_SUGGESTIONS=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n'
open(dst, 'w', encoding='utf8').write(js)
assert len(out) == len(tr), 'translation count mismatch'
print(len(out), 'suggestions')
