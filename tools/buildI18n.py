#!/usr/bin/env python3
"""Builds www/i18n.js from the dictionary files (key language first, then the other languages)."""
import json, sys, pathlib

LANGS = ['de', 'en', 'ru', 'pt', 'nl', 'fr', 'it', 'es', 'pl', 'uk', 'zh-cn']
src = pathlib.Path(sys.argv[1])
entries = []
for f in sorted(src.glob('dict*.txt')):
    en_key = False
    for line in f.read_text(encoding='utf8').split('\n'):
        if not line.strip():
            continue
        if line.strip() == '#EN':
            en_key = True
            continue
        p = line.split('|')
        if en_key:  # key(en)|de|ru|pt|nl|fr|it|es|pl|uk|zh-cn
            p = [p[1], p[0]] + p[2:]
        assert len(p) == 11, (f.name, len(p), p[0][:50])
        entries.append(p)

head = r"""/*
 * ShelfMate app translations (generated by tools/buildI18n.py, do not edit by hand).
 * Texts of the app are German; the entries translate them (and the English server messages) into the ioBroker language.
 */
(function () {
  'use strict';
  var LANGS = %s;
  var E = %s;
  var LOCALES = { de: 'de-DE', en: 'en-GB', ru: 'ru-RU', pt: 'pt-PT', nl: 'nl-NL', fr: 'fr-FR', it: 'it-IT', es: 'es-ES', pl: 'pl-PL', uk: 'uk-UA', 'zh-cn': 'zh-CN' };
  var lang = 'de';
  var exact = {};
  var pats = [];
  var counted = [];
  function esc(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&%s'); }
  E.forEach(function (row, idx) {
    var hasPh = /\{\d\}/.test(row[0]);
    if (!hasPh) {
      row.forEach(function (txt) { if (txt && !(txt in exact)) exact[txt] = idx; });
      return;
    }
    row.forEach(function (txt) {
      var n = 0;
      var re = new RegExp('^' + esc(txt).replace(/\\\{(\d)\\\}/g, function () { n++; return '([\\s\\S]+?)'; }) + '$');
      pats.push({ re: re, idx: idx, len: txt.length });
    });
    var m = /^\{1\} ([A-Za-zÄÖÜäöüß]+)$/.exec(row[0]);
    if (m) {
      row.forEach(function (txt) {
        var w = /^\{1\} (.+)$/.exec(txt);
        if (w) counted.push({ re: new RegExp('(\\d+(?:[.,]\\d+)?) ' + esc(w[1]) + '(?![A-Za-zÄÖÜäöüß])', 'g'), idx: idx });
      });
    }
  });
  pats.sort(function (a, b) { return b.len - a.len; });
  function fill(tpl, caps) { return tpl.replace(/\{(\d)\}/g, function (_, i) { return caps[Number(i) - 1] === undefined ? '' : caps[Number(i) - 1]; }); }
  var L = function () { return LANGS.indexOf(lang); };
  function lookup(core) {
    if (Object.prototype.hasOwnProperty.call(exact, core)) return E[exact[core]][L()];
    for (var i = 0; i < pats.length; i++) {
      var m = pats[i].re.exec(core);
      if (m) {
        var caps = m.slice(1).map(function (c) { return lookup(c) || c; });
        return fill(E[pats[i].idx][L()], caps);
      }
    }
    var out = core, changed = false;
    counted.forEach(function (c) {
      var tpl = E[c.idx][L()];
      var w = /^\{1\} (.+)$/.exec(tpl);
      if (!w) return;
      out = out.replace(c.re, function (_, n) { changed = true; return n + ' ' + w[1]; });
    });
    return changed ? out : null;
  }
  function tr(s) {
    if (typeof s !== 'string') return s;
    var m = /^(\s*)([\s\S]*?)(\s*)$/.exec(s);
    if (!m[2]) return s;
    var t = lookup(m[2]);
    return t === null || t === undefined ? s : m[1] + t + m[3];
  }
  var ATTRS = ['placeholder', 'title', 'aria-label', 'alt'];
  function walk(root) {
    if (!root) return;
    if (root.nodeType === 3) { var v = tr(root.nodeValue); if (v !== root.nodeValue) root.nodeValue = v; return; }
    if (root.nodeType !== 1) return;
    if (root.tagName === 'SCRIPT' || root.tagName === 'STYLE') return;
    ATTRS.forEach(function (a) {
      if (root.hasAttribute && root.hasAttribute(a)) { var o = root.getAttribute(a), n = tr(o); if (n !== o) root.setAttribute(a, n); }
    });
    for (var c = root.firstChild; c; c = c.nextSibling) walk(c);
  }
  var obs = null;
  function start() {
    if (obs || !document.body) return;
    walk(document.body);
    obs = new MutationObserver(function (list) {
      list.forEach(function (r) {
        if (r.type === 'characterData') walk(r.target);
        else if (r.type === 'attributes') walk(r.target);
        else r.addedNodes.forEach(walk);
      });
    });
    obs.observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ATTRS });
  }
  function norm(l) {
    l = String(l || '').toLowerCase().replace('_', '-');
    if (LANGS.indexOf(l) >= 0) return l;
    var short = l.split('-')[0];
    return LANGS.indexOf(short) >= 0 ? short : (short === 'zh' ? 'zh-cn' : 'en');
  }
  function set(l) {
    var n = norm(l);
    var changed = n !== lang;
    lang = n;
    document.documentElement.lang = n === 'zh-cn' ? 'zh-CN' : n;
    try { localStorage.setItem('shelfmate-lang', n); } catch (e) { /* ignore */ }
    if (document.body) { start(); if (changed) walk(document.body); }
    document.title = tr(document.title);
  }
  var stored = null;
  try { stored = localStorage.getItem('shelfmate-lang'); } catch (e) { /* ignore */ }
  lang = norm(stored || navigator.language || 'en');
  if (!stored && lang === 'en' && /^de/i.test(navigator.language || '')) lang = 'de';
  window.I18N = { tr: tr, set: set, get: function () { return lang; }, locale: function () { return LOCALES[lang] || 'en-GB'; }, walk: walk };
  document.documentElement.lang = lang === 'zh-cn' ? 'zh-CN' : lang;
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', function () { set(lang); }); else set(lang);
})();
"""
out = head % (json.dumps(LANGS), json.dumps(entries, ensure_ascii=False), '')
pathlib.Path(sys.argv[2]).write_text(out, encoding='utf8')
print(len(entries), 'entries,', len(out), 'bytes')
