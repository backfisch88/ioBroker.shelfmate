"""Builds lib/pluData.js and lib/pluNames.js from the IFPS list (commodities.xlsx) and names.txt.

Usage: python3 tools/plu/buildPlu.py
Needs: pip install openpyxl
"""
import json
import os
import sys
from collections import OrderedDict

import openpyxl

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
from mapping import name_of  # noqa: E402

LANGS = ['en', 'de', 'ru', 'pt', 'nl', 'fr', 'it', 'es', 'pl', 'uk', 'zh-cn']

wb = openpyxl.load_workbook(os.path.join(here, 'commodities.xlsx'), read_only=True)
rows = list(wb.active.iter_rows(values_only=True))
head = rows[0]
rows = [dict(zip(head, r)) for r in rows[1:]]

groups = OrderedDict()
for r in rows:
    if r['Deleted_at'] or r['Status'] != 'Approved':
        continue
    name = name_of(r['Category'], r['Commodity'], (r['Variety'] or '').strip())
    groups.setdefault(name, set()).add(int(r['Plu']))


def ranges(nums):
    nums = sorted(nums)
    out, i = [], 0
    while i < len(nums):
        j = i
        while j + 1 < len(nums) and nums[j + 1] == nums[j] + 1:
            j += 1
        out.append(str(nums[i]) if i == j else f'{nums[i]}-{nums[j]}')
        i = j + 1
    return ' '.join(out)


names = OrderedDict()
for line in open(os.path.join(here, 'names.txt'), encoding='utf-8'):
    if not line.strip() or line.startswith('#'):
        continue
    parts = line.rstrip('\n').split('|')
    assert len(parts) == 12, line
    names[parts[0]] = parts[1:]

missing = [n for n in groups if n not in names]
assert not missing, missing
unused = [n for n in names if n not in groups]
assert not unused, unused

data = [[n, ranges(c)] for n, c in sorted(groups.items())]
lib = os.path.join(here, '..', '..', 'lib')
with open(os.path.join(lib, 'pluData.js'), 'w', encoding='utf-8') as f:
    f.write("""'use strict';

/**
 * Produce look-up (PLU) numbers of the IFPS list (International Federation for Produce Standards, 2024), reduced to
 * the product with its English name. Entries: [name, numbers], numbers separated by blanks, "a-b" is a range.
 * Numbers that retailers assign themselves are listed under their product as well (for example 4237-4238 bananas).
 * Generated by tools/plu/buildPlu.py, do not edit.
 */
module.exports = """ + json.dumps(data, ensure_ascii=False, indent=4) + ';\n')
tr = OrderedDict()
for n, parts in names.items():
    tr[n] = OrderedDict(zip(LANGS, parts))
with open(os.path.join(lib, 'pluNames.js'), 'w', encoding='utf-8') as f:
    f.write("""'use strict';

/**
 * Names of the produce in the languages of the adapter, by English name. Generated by tools/plu/buildPlu.py from
 * tools/plu/names.txt, do not edit.
 */
module.exports = """ + json.dumps(tr, ensure_ascii=False, indent=4) + ';\n')
print(len(data), 'products,', sum(len(v) for v in groups.values()), 'numbers')
